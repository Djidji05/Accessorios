/**
 * Case-insensitive lookup cache built lazily per language
 */
const LOWERCASE_PHRASE_CACHE: Partial<Record<Language, Record<string, string>>> = {};

function getLowercasePhraseDict(lang: Language): Record<string, string> {
  if (!LOWERCASE_PHRASE_CACHE[lang]) {
    const raw = PHRASE_DICTIONARY[lang] || {};
    const map: Record<string, string> = {};
    for (const [k, v] of Object.entries(raw)) {
      map[k.trim().toLowerCase()] = v;
    }
    LOWERCASE_PHRASE_CACHE[lang] = map;
  }
  return LOWERCASE_PHRASE_CACHE[lang]!;
}

/**
 * Universal text translation helper function.
 * Matches typed translation keys, dictionary phrases, or returns fallback.
 */
export function translateText(keyOrPhrase: string, lang: Language, fallback?: string): string {
  if (!keyOrPhrase) return fallback || '';
  if (lang === 'FR') {
    // If it's a key in FR dictionary, return translated value, else return keyOrPhrase
    const frDict = translations.FR as unknown as Record<string, string>;
    if (frDict[keyOrPhrase]) return frDict[keyOrPhrase];
    return fallback || keyOrPhrase;
  }

  // Check typed keys in target language
  const targetDict = (translations[lang] || translations.FR) as unknown as Record<string, string>;
  if (targetDict[keyOrPhrase]) {
    return targetDict[keyOrPhrase];
  }

  // Check phrase dictionary by keyOrPhrase OR by fallback string!
  const phraseDict = PHRASE_DICTIONARY[lang];
  if (phraseDict) {
    // Exact match on keyOrPhrase
    if (phraseDict[keyOrPhrase]) {
      return phraseDict[keyOrPhrase];
    }
    // Trimmed match on keyOrPhrase
    const trimmed = keyOrPhrase.trim();
    if (phraseDict[trimmed]) {
      return phraseDict[trimmed];
    }
    // Match on fallback (when callers pass t('custom_key', 'Texte en français'))
    if (fallback) {
      if (phraseDict[fallback]) {
        return phraseDict[fallback];
      }
      const trimmedFallback = fallback.trim();
      if (phraseDict[trimmedFallback]) {
        return phraseDict[trimmedFallback];
      }
    }
    // Case-insensitive match on keyOrPhrase or fallback
    const lowerDict = getLowercasePhraseDict(lang);
    const lowerKey = trimmed.toLowerCase();
    if (lowerDict[lowerKey]) {
      return lowerDict[lowerKey];
    }
    if (fallback) {
      const lowerFallback = fallback.trim().toLowerCase();
      if (lowerDict[lowerFallback]) {
        return lowerDict[lowerFallback];
      }
    }
  }

  // Check French fallback key
  const frDict = translations.FR as unknown as Record<string, string>;
  if (frDict[keyOrPhrase]) {
    return frDict[keyOrPhrase];
  }

  return fallback || keyOrPhrase;
}
